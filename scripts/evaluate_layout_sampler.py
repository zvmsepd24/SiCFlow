"""Sampling the layout of the two-scale model: how the layout sampler changes the fibers drawn on it.

The fiber model of seed 1 draws fields of 1024 x 1024 px conditioned on (a) real layouts of the training
band and of the held-out band and (b) layouts generated by the layout model with different samplers
(number of Heun steps, and rho of the time grid t_i = 1 - (1 - i/n)^rho; rho < 1 places shorter steps near
the noise). For each set: roughness of the layouts (mean squared difference between neighbouring layout
pixels, per channel), 99th percentile of the fiber channel, and fiber fraction, pore fraction, median
fiber diameter and two values of the fiber two-point correlation of the segmented fields: the neighbour
peak across the bands and the mean along the bands at 100-300 um.
Usage: python scripts/evaluate_layout_sampler.py -> results/sic/layout_sampler.json
"""
import json
import sys
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from genmicro import fibers, sic  # noqa: E402
from genmicro.descriptors import autocorrelation  # noqa: E402
from genmicro.phases import phases  # noqa: E402
from genmicro.scores import load_model  # noqa: E402
from genmicro.train import sample  # noqa: E402
from genmicro.twoscale import DOWN, FIBER_RHO, FIBER_STEPS, ImageConditioned, fraction_fields, upsample  # noqa: E402

TW = ROOT / "results/sic/twoscale"
S, N = 1024, 8
SAMPLERS = [(16, 0.7), (16, 1.0), (32, 1.0), (64, 1.0)]
UM = 1.04


def roughness(lay):
    """Mean squared difference between neighbouring layout pixels, per channel."""
    dy = (lay[:, :, 1:, :] - lay[:, :, :-1, :]).square().mean((0, 2, 3))
    dx = (lay[:, :, :, 1:] - lay[:, :, :, :-1]).square().mean((0, 2, 3))
    return ((dx + dy) / 2).tolist()


@torch.no_grad()
def draw(fine, lay, g):
    out = []
    for i in range(len(lay)):
        with torch.autocast("cuda", torch.bfloat16):
            z = torch.randn(1, 1, lay.shape[-2] * DOWN, lay.shape[-1] * DOWN, device="cuda", generator=g)
            out.append(sample(fine, z, FIBER_STEPS, cond=upsample(lay[i:i + 1]), rho=FIBER_RHO).float()[0, 0].cpu().numpy())
    return out


def correlation(ph):
    """Neighbour peak of the fiber two-point correlation across the bands (maximum over 14-22 px) and its
    mean along the bands over 96-288 px (100-300 um), pooled over the images."""
    fib = [torch.as_tensor(p == 1).float().cuda()[None] for p in ph]
    p = float(np.mean([f.mean().item() for f in fib]))
    c = torch.stack([autocorrelation(f, periodic=False)[0, :300, :300] for f in fib]).mean(0)
    c = ((c - p * p) / (p - p * p)).cpu().numpy()
    return float(c[14:23, 0].max()), float(c[0, 96:289].mean())


def summary(lay, images):
    ph = [phases(im) for im in images]
    peak, along = correlation(ph)
    tiles = np.stack([im[y:y + 256, x:x + 256] for im in images for y in range(0, im.shape[0] - 255, 256)
                      for x in range(0, im.shape[1] - 255, 256)])
    return dict(roughness=roughness(lay), fiber_channel_q99=float(torch.quantile(lay[:, 0].flatten()[::7], 0.99)),
                fiber_fraction=float(np.mean([(p == 1).mean() for p in ph])), pore_fraction=float(np.mean([(p == 2).mean() for p in ph])),
                median_diameter_um=float(np.median(fibers.collect(tiles)["diameter"]) * UM), neighbour_peak_across=peak,
                correlation_along_100_300um=along)


def main():
    plane = sic.load_plane()
    coarse = load_model(TW / "layout_s1.pt")
    fine = ImageConditioned(load_model(TW / "fiber_s1.pt")).eval()
    m = S // DOWN
    band_lay = fraction_fields(plane[:, :2640])[0]
    h, w = band_lay.shape[-2:]
    rng = np.random.default_rng(0)
    real = torch.stack([band_lay[:, y:y + m, x:x + m] for y, x in zip(rng.integers(0, h - m, N), rng.integers(0, w - m, N))])
    held_lay = fraction_fields(plane[:S, 2768:2768 + 824])
    out = {}
    g = torch.Generator(device="cuda").manual_seed(0)
    out["real layouts, training band"] = summary(real, draw(fine, real, g))
    out["real layout, held-out band"] = summary(held_lay, draw(fine, held_lay, g))
    held = plane[:S, 2768:2768 + 824].cpu().numpy()
    ph = phases(held)
    peak, along = correlation([ph])
    out["held-out band itself"] = dict(fiber_fraction=float((ph == 1).mean()), pore_fraction=float((ph == 2).mean()),
                                       median_diameter_um=float(np.median(fibers.collect(np.stack(
                                           [held[y:y + 256, x:x + 256] for y in range(0, S - 255, 256) for x in range(0, 824 - 255, 256)]))["diameter"]) * UM),
                                       neighbour_peak_across=peak, correlation_along_100_300um=along)
    for steps, rho in SAMPLERS:
        g = torch.Generator(device="cuda").manual_seed(1)
        with torch.no_grad(), torch.autocast("cuda", torch.bfloat16):
            lay = sample(coarse, torch.randn(N, 2, m, m, device="cuda", generator=g), steps, rho=rho).float()
        out[f"generated layouts, {steps} steps, rho {rho:g}"] = summary(lay, draw(fine, lay, g))
        print(steps, rho, json.dumps(out[f"generated layouts, {steps} steps, rho {rho:g}"]), flush=True)
    (ROOT / "results/sic/layout_sampler.json").write_text(json.dumps(out, indent=1))
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    torch.cuda.set_per_process_memory_fraction(0.25)
    main()
