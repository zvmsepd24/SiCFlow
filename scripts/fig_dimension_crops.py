"""Supplementary figure: the intrinsic dimension of real windows against the number of crops in the region they are
cut from, at both scales.

a: fiber scale: Levina-Bickel dimension of clouds of 512 two-point curves of 64 px windows cut from the training tiles
   of sets A and B at the five training areas (mean of A and B and of three replicates), and of held-out windows.
b: tow scale: dimension of clouds of 512 windows of 0.53 mm of the fiber-fraction layout (autocovariance along and
   across) cut from regions of the training band of increasing width (full height), from its halves, from the whole
   band and from the held-out band; and of windows generated by layout models after 500 steps (halves and whole band).
x axis: area of the region divided by the crop area. At the fiber scale the dimension of real windows levels off at
the value of held-out windows within the training areas; at the tow scale it is still rising at the whole band.
Data: results/sic/convergence/rep*.json; results/sic/towscale/dimension.json.
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.figstyle import DOUBLE, INK, INK2, SERIES, panel_label, plain_log_axis, plt  # noqa: E402
from scripts.fig_convergence import load, series  # noqa: E402

CROP_MM2 = (64 * 1.04e-3) ** 2


def main():
    reps = load()
    dim = json.loads((ROOT / "results/sic/towscale/dimension.json").read_text())
    fig, axs = plt.subplots(1, 2, figsize=(DOUBLE * 0.8, 0.3 * DOUBLE))
    plt.subplots_adjust(wspace=0.38, left=0.1, right=0.98, bottom=0.22, top=0.88)
    ax = axs[0]
    x = np.array([r["area_mm2"] for r in reps[0]]) / CROP_MM2
    m, lo, hi = series(reps, lambda r: np.mean([r["dimension"]["training"][s]["two_point"] for s in "AB"]))
    ax.fill_between(x, lo, hi, color=INK2, alpha=0.2, lw=0)
    ax.plot(x, m, "o--", color=INK2, ms=3, label="windows of the training tiles")
    held = series(reps, lambda r: r["dimension"]["held_out"]["two_point"])[0].mean()
    ax.axhline(held, color=INK, ls=":", lw=1.0, label="held-out windows")
    ax.set_xscale("log")
    plain_log_axis(ax, "x", [3, 10, 30, 100, 300, 1000])
    ax.set_xlabel("region area / crop area (64 px crops)")
    ax.set_ylabel("intrinsic dimension")
    ax.set_title("fiber scale: two-point curves", fontsize=7, pad=3)
    ax.legend(fontsize=5.6, loc="lower right")
    panel_label(ax, "a", x=-0.25)
    ax = axs[1]
    rr = dim["real"]
    left = sorted((v["crops"], v["two_point"]["mean"], v["two_point"]["sd"]) for k, v in rr.items() if k.startswith("left ") and k != "left half")
    c, mm, sd = np.array(left).T
    ax.errorbar(c, mm, yerr=sd, fmt="o--", color=INK2, ms=3, lw=1.0, capsize=0, label="windows of the training band, regions\nof increasing width")
    ax.plot([rr["right half"]["crops"]], [rr["right half"]["two_point"]["mean"]], "s", color=INK2, mfc="white", ms=4,
            label="right half")
    ax.plot([rr["held-out band"]["crops"]], [rr["held-out band"]["two_point"]["mean"]], "D", color=INK, ms=4, mfc="white",
            label="held-out band")
    g = dim["generated"]
    early = [g[k]["two_point"]["mean"] for k in ("layouts/A500_s1", "layouts/A500_s2", "layouts/B500_s1") if k in g]
    full = [g[k]["two_point"]["mean"] for k in ("layouts/steps500_s1", "layouts/steps500_s2") if k in g]
    if early:
        ax.errorbar([12], [np.mean(early)], yerr=[[np.mean(early) - min(early)], [max(early) - np.mean(early)]], fmt="o",
                    color=SERIES[1], ms=4, capsize=0, label="layout models after 500 steps")
    if full:
        ax.errorbar([24], [np.mean(full)], yerr=[[np.mean(full) - min(full)], [max(full) - np.mean(full)]], fmt="o",
                    color=SERIES[1], ms=4, capsize=0)
    ax.set_xscale("log")
    plain_log_axis(ax, "x", [3, 5, 10, 20, 30])
    ax.set_xlim(3.5, 32)
    ax.set_ylim(0, 8)
    ax.set_xlabel("region area / crop area (0.53 mm crops)")
    ax.set_ylabel("intrinsic dimension")
    ax.set_title("tow scale: layout autocovariance", fontsize=7, pad=3)
    ax.legend(fontsize=5.3, loc="upper left")
    panel_label(ax, "b", x=-0.25)
    fig.savefig(ROOT / "figures/figS_dimension_crops.pdf", dpi=300)
    fig.savefig(ROOT / "figures/figS_dimension_crops.png", dpi=220)


if __name__ == "__main__":
    main()
